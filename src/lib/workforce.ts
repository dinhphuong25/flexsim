// Khởi tạo Ma trận kỹ năng mặc định (34 vị trí x 27 công đoạn)
export function getInitialSkillMatrix(): Record<string, Record<string, SkillLevel>> {
  const matrix: Record<string, Record<string, SkillLevel>> = {};

  for (const pos of INITIAL_WORKFORCE_POSITIONS) {
    matrix[pos.positionCode] = {};
    for (let i = 1; i <= 27; i++) {
      const stageCode = `CD${String(i).padStart(2, '0')}`;
      if (pos.workerType === 'FIXED') {
        if (pos.stageCode === stageCode) {
          matrix[pos.positionCode][stageCode] = 'THUC_HIEN_DUOC';
        } else {
          matrix[pos.positionCode][stageCode] = 'CHUA_DANH_GIA';
        }
      } else {
        // Floating workers
        if (pos.positionCode === 'CN31') {
          if (stageCode === 'CD04') matrix[pos.positionCode][stageCode] = 'THUC_HIEN_DUOC';
          else if (stageCode === 'CD05') matrix[pos.positionCode][stageCode] = 'CO_THE_HO_TRO';
          else matrix[pos.positionCode][stageCode] = 'CHUA_DANH_GIA';
        } else if (pos.positionCode === 'CN32') {
          if (stageCode === 'CD11') matrix[pos.positionCode][stageCode] = 'THUC_HIEN_DUOC';
          else if (stageCode === 'CD12') matrix[pos.positionCode][stageCode] = 'CO_THE_HO_TRO';
          else matrix[pos.positionCode][stageCode] = 'CHUA_DANH_GIA';
        } else if (pos.positionCode === 'CN33') {
          if (stageCode === 'CD13') matrix[pos.positionCode][stageCode] = 'THUC_HIEN_DUOC';
          else if (stageCode === 'CD14') matrix[pos.positionCode][stageCode] = 'CO_THE_HO_TRO';
          else matrix[pos.positionCode][stageCode] = 'CHUA_DANH_GIA';
        } else if (pos.positionCode === 'CN34') {
          if (stageCode === 'CD16') matrix[pos.positionCode][stageCode] = 'THUC_HIEN_DUOC';
          else if (stageCode === 'CD17') matrix[pos.positionCode][stageCode] = 'CO_THE_HO_TRO';
          else matrix[pos.positionCode][stageCode] = 'CHUA_DANH_GIA';
        }
      }
    }
  }

  return matrix;
}

